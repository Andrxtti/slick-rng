# Lift the old project's grading function, text unchanged, into beta1's editor (Editor/OldGrading.cs), so GradeCheck can
# run the old and new code side by side on every hand in the library. Re-run if the old Play.cs ever changes.
#   python beta1/tools/grade_check_gen.py
import os, re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = open(os.path.join(os.path.dirname(ROOT), "unity", "Assets", "Dream", "Scripts", "Game", "Play.cs"), encoding="utf-8").read()
steps = re.search(r"^.*static readonly Dictionary<string, double\[\]> LossSteps.*$", src, re.M).group(0)
start = src.index("        public static (string lab, double? loss, int bestIdx) LabelFor(")
depth, i = 0, src.index("{", start)
while True:
    if src[i] == "{": depth += 1
    elif src[i] == "}":
        depth -= 1
        if depth == 0: break
    i += 1
method = src[start:i + 1]
out = f"""// GENERATED by tools/grade_check_gen.py: the old project's Play.LabelFor and its loss steps, copied as text from
// unity/Assets/Dream/Scripts/Game/Play.cs. Editor-only; used by GradeCheck to prove beta1 grades the same.
using System;
using System.Collections.Generic;
using System.Linq;

namespace Dream.EditorTools
{{
    public static class OldGrading
    {{
{steps}
{method}
    }}
}}
"""
p = os.path.join(ROOT, "Assets", "Dream", "Editor", "OldGrading.cs")
open(p, "w", encoding="utf-8").write(out)
print("wrote", p, len(method), "chars")
